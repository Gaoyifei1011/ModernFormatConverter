namespace ModernFormatConverter.Extensions.DataType.Class
{
    /// <summary>
    /// 图片 EXIF 信息
    /// </summary>
    public class ImageExifInfo
    {
        /// <summary>
        /// 照相机制造商
        /// </summary>
        public string CameraManufacturer { get; set; }

        /// <summary>
        /// 照相机型号
        /// </summary>
        public string CameraModel { get; set; }

        /// <summary>
        /// 曝光时间
        /// </summary>
        public string ExposureTime { get; set; }

        /// <summary>
        /// 拍摄日期
        /// </summary>
        public string DateTaken { get; set; }

        /// <summary>
        /// 快门速度
        /// </summary>
        public string ShutterSpeed { get; set; }

        /// <summary>
        /// 测光模式
        /// </summary>
        public string MeteringMode { get; set; }

        /// <summary>
        /// 闪光灯模式
        /// </summary>
        public string FlashMode { get; set; }

        /// <summary>
        /// 水平分辨率
        /// </summary>
        public string XResolution { get; set; }

        /// <summary>
        /// 垂直分辨率
        /// </summary>
        public string YResolution { get; set; }

        /// <summary>
        /// 分辨率单位
        /// </summary>
        public string ResolutionUnit { get; set; }

        /// <summary>
        /// 宽度
        /// </summary>
        public string Width { get; set; }

        /// <summary>
        /// 高度
        /// </summary>
        public string Height { get; set; }

        /// <summary>
        /// 光圈 F 值
        /// </summary>
        public string FNumber { get; set; }

        /// <summary>
        /// 曝光程序
        /// </summary>
        public string ExposureProgram { get; set; }

        /// <summary>
        /// 光圈灵敏度
        /// </summary>
        public string SpectralSense { get; set; }

        /// <summary>
        /// ISO 速度
        /// </summary>
        public string ISOSpeed { get; set; }

        /// <summary>
        /// 光圈转换函数
        /// </summary>
        public string OECF { get; set; }

        /// <summary>
        /// 版本
        /// </summary>
        public string Version { get; set; }

        /// <summary>
        /// 压缩配置
        /// </summary>
        public string CompressionConfig { get; set; }

        /// <summary>
        /// 压缩的位/像素
        /// </summary>
        public string CompressionBitsPerPixel { get; set; }

        /// <summary>
        /// 光圈值
        /// </summary>
        public string Aperture { get; set; }

        /// <summary>
        /// 亮度
        /// </summary>
        public string Brightness { get; set; }

        /// <summary>
        /// 曝光补偿
        /// </summary>
        public string ExposureCompensation { get; set; }

        /// <summary>
        /// 最大光圈值
        /// </summary>
        public string MaxAperture { get; set; }

        /// <summary>
        /// 目标距离
        /// </summary>
        public string SubjectDist { get; set; }

        /// <summary>
        /// 光源
        /// </summary>
        public string LightSource { get; set; }

        /// <summary>
        /// 焦距
        /// </summary>
        public string FocalLength { get; set; }

        /// <summary>
        /// FiashPix 版本
        /// </summary>
        public string FlashPixVersion { get; set; }

        /// <summary>
        /// 颜色表示
        /// </summary>
        public string ColorIndicates { get; set; }

        /// <summary>
        /// 互操作性索引
        /// </summary>
        public string Interop { get; set; }

        /// <summary>
        /// 闪光灯能量
        /// </summary>
        public string FlashEnergy { get; set; }

        /// <summary>
        /// 空间频率响应
        /// </summary>
        public string SpatialFrequencyResponse { get; set; }

        /// <summary>
        /// 焦距水平分辨率
        /// </summary>
        public string FocalXRes { get; set; }

        /// <summary>
        /// 焦距垂直分辨率
        /// </summary>
        public string FocalYRes { get; set; }

        /// <summary>
        /// 焦距分辨率单位
        /// </summary>
        public string FocalResUnit { get; set; }

        /// <summary>
        /// 35mm 焦距
        /// </summary>
        public string FocalLengthIn35mmFormat { get; set; }

        /// <summary>
        /// 曝光指数
        /// </summary>
        public string ExposureIndex { get; set; }

        /// <summary>
        /// 感光方式
        /// </summary>
        public string SenseMethod { get; set; }

        /// <summary>
        /// 场景类型
        /// </summary>
        public string SceneType { get; set; }

        /// <summary>
        /// 色彩滤镜阵列
        /// </summary>
        public string CfaPattern { get; set; }

        /// <summary>
        /// 白平衡
        /// </summary>
        public string WhiteBalance { get; set; }
    }
}
